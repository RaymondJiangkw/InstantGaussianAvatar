class ASPPPooling(nn.Sequential):
    def __init__(self, in_channels, out_channels):
        super().__init__(
            nn.AdaptiveAvgPool2d(1),
            nn.Conv2d(in_channels, out_channels, kernel_size=1, bias=False),
            nn.ReLU(),
        )

    def forward(self, x):
        size = x.shape[-2:]
        for mod in self:
            x = mod(x)
        return F.interpolate(x, size=size, mode="bilinear", align_corners=False)


class ASPP(nn.Module):
    def __init__(self, in_channels, out_channels, atrous_rates, separable=False):
        super(ASPP, self).__init__()
        modules = []
        modules.append(
            nn.Sequential(
                nn.Conv2d(in_channels, out_channels, 1, bias=False),
                nn.ReLU(),
            )
        )

        rate1, rate2, rate3 = tuple(atrous_rates)
        self.ASPPConvModule = ASPPConv if not separable else ASPPSeparableConv

        modules.append(self.ASPPConvModule(in_channels, out_channels, rate1))
        modules.append(self.ASPPConvModule(in_channels, out_channels, rate2))
        modules.append(self.ASPPConvModule(in_channels, out_channels, rate3))
        modules.append(ASPPPooling(in_channels, out_channels))

        self.convs = nn.ModuleList(modules)

        self.project = nn.Sequential(
            nn.Conv2d(5 * out_channels, out_channels, kernel_size=1, bias=False),
            nn.ReLU(),
        )

    def forward(self, x):
        res = []
        for conv in self.convs:
            res.append(conv(x))
        res = torch.cat(res, dim=1)
        return self.project(res)


class DeepLabV3Decoder(nn.Module):
    def __init__(self, in_channels, out_channels=256, atrous_rates=(12, 24, 36)):
        super().__init__()
        self.aspp = ASPP(in_channels, out_channels, atrous_rates)
        self.project = nn.Sequential(
            nn.Conv2d(out_channels, out_channels, 3, padding=1, bias=False),
            nn.ReLU(),
        )
        self.out_channels = out_channels

    def forward(self, feat):
        feat = self.aspp(feat)
        return self.project(feat)

class DeepLabV3(nn.Module):
    def __init__(self, in_dim: int = 3) -> None:
        super().__init__()
        self.in_dim = in_dim
        self.preprocessing_fn = get_preprocessing_fn() # Expect [0, 1]
        # Build encoder
        self.encoder = ResNetEncoder()
        self.encoder.set_in_channels(in_dim + 2, pretrained=True)
        self.encoder.make_dilated(8)

        # Build decoder
        self.decoder = DeepLabV3Decoder(
            self.encoder._out_channels[-1], 
        )
    def forward(self, x: torch.Tensor) -> torch.Tensor:
        assert_shape(x, [None, self.in_dim, None, None]) # Expect [-1, 1] range
        x = x.detach().clone()
        x[:, :3, :, :] = self.preprocessing_fn(x[:, :3, :, :] / 2 + .5)
        x = torch.cat((
            x, F.affine_grid(torch.eye(2, 3)[None].to(x.device).expand(len(x), -1, -1), x.shape, align_corners=False).permute(0, 3, 1, 2).contiguous()
        ), dim=1)
        feat = self.encoder(x)
        
        # Shallow & Deep Features
        return feat[1], self.decoder(feat[-1]) # (B, 256, H?, W?)

